"""Per-world results, cluster-bootstrap intervals for larger
dependence units, and the zero / non-zero split of the G2 counting questions.

python methods/cluster_stats.py > paper/tables_cluster_stats.md

Units of dependence (each a cluster for a paired bootstrap of the accuracy difference, 10,000 resamples, seed 0):
  state      question subject (world, person) and family (world, surname of the subject)
  continuity pair subject (world, person) and family
  G2         questions linked by shared gold evidence events (connected components within a world)
The per-world rows show whether the pooled effect holds in each world separately.  Reads the same result files as
methods/agy_replication_report.py (first record per question; continuity label errors dropped).
"""
import json
import os
import random
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "methods"))
sys.path.insert(0, os.path.join(ROOT, "bench"))
from agy_replication_report import READERS, load, mcnemar  # noqa: E402

TASKS = [("State tracking, about 0.5M tokens", ["saga_v5_s7", "saga_v5_s8"], "mem-cmm4", ["mem-pbm25", "hybrid"], False),
         ("Continuity checking (pairs)", ["cont2_s7", "cont2_s8"], "mem-cmm4", ["mem-pbm25", "hybrid"], True),
         ("G2 counting, fresh worlds", ["agg2_s11", "agg2_s12"], "mem-evx4v5",
          ["oracle_para", "oracle_para_cert", "mem-cmm4", "mem-pbm25", "hybrid"], False)]
WORLD = {"saga_v5_s7": "saga_v5_s7", "saga_v5_s8": "saga_v5_s8", "cont2_s7": "saga_v5_s7", "cont2_s8": "saga_v5_s8",
         "agg2_s11": "saga_v5_s11", "agg2_s12": "saga_v5_s12"}


def gold(ds):
    return {json.loads(l)["qid"]: json.loads(l) for l in open(os.path.join(ROOT, "data", ds, "questions_GOLD.jsonl"),
                                                               encoding="utf-8")}


def surname(ds, pid):
    w = json.load(open(os.path.join(ROOT, "data", WORLD[ds], "world_GOLD.json"), encoding="utf-8"))
    p = w["persons"].get(pid)
    return p["surname"] if p else pid


def evidence_components(ds, qids, g):
    parent = {q: q for q in qids}

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x
    by_ev = defaultdict(list)
    for q in qids:
        for e in g[q].get("evidence_core") or g[q].get("evidence") or []:
            by_ev[e].append(q)
    for qs in by_ev.values():
        for q in qs[1:]:
            parent[find(q)] = find(qs[0])
    return {q: (ds, find(q)) for q in qids}


def link_components(keys, tokens):
    """union-find over keys: two keys are in one component when they share any token (keys must be within one world;
    the world is part of every token through the key's world prefix)"""
    parent = {k: k for k in keys}

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x
    first = {}
    for k in keys:
        for t in tokens(k):
            t = (k[0], t)
            if t in first:
                parent[find(k)] = find(first[t])
            else:
                first[t] = k
    return {k: find(k) for k in keys}


def units(ds, m, r, paired, g):
    """unit key -> correct (question, or pair), plus the question ids behind each unit"""
    d = load(ds, m, r)
    out, members = {}, {}
    if paired:
        import check_continuity_labels
        bad = {b[0] for b in check_continuity_labels.check(ds)[0]}
        by = defaultdict(list)
        for qid, x in d.items():
            if qid in g and qid not in bad:
                by[g[qid]["pair"]].append((qid, x))
        for p, xs in by.items():
            if len(xs) == 2:
                out[(ds, p)] = int(all(x["correct"] for _, x in xs))
                members[(ds, p)] = [q for q, _ in xs]
    else:
        for qid, x in d.items():
            out[(ds, qid)] = int(x["correct"])
            members[(ds, qid)] = [qid]
    return out, members


def boot(diff_by_cluster, reps=10000, seed=0):
    rng = random.Random(seed)
    # clusters in a fixed order (a set-derived order would change the intervals between runs)
    cl = [diff_by_cluster[c] for c in sorted(diff_by_cluster, key=repr)]  # (sum of differences, number of units)
    n_units = sum(c[1] for c in cl)
    est = sum(c[0] for c in cl) / n_units
    bs = []
    for _ in range(reps):
        s = [cl[rng.randrange(len(cl))] for _ in cl]
        bs.append(sum(x[0] for x in s) / max(1, sum(x[1] for x in s)))
    bs.sort()
    return est, bs[int(0.025 * reps)], bs[int(0.975 * reps) - 1]


def main():
    print("# Per-world results, dependence-aware intervals, zero / non-zero split\n")
    print("Generated by methods/cluster_stats.py (no model calls). Differences are first method minus other, "
          "in accuracy points; intervals are paired cluster-bootstrap 95% intervals (10,000 resamples).\n")
    for title, dss, base, others, paired in TASKS:
        print(f"## {title}\n")
        gs = {ds: gold(ds) for ds in dss}
        print("| Reader | other | world | n | base | other | w/l | exact p (uncorrected) |")
        print("|---|---|---|---|---|---|---|---|")
        clus_rows = []
        for rname, r in READERS:
            u = {}
            mem = {}
            for m in [base] + others:
                u[m], mem[m] = {}, {}
                for ds in dss:
                    a, b = units(ds, m, r, paired, gs[ds])
                    u[m].update(a)
                    mem[m].update(b)
            for o in others:
                common = set(u[base]) & set(u[o])
                if not common:
                    continue
                for ds in dss + ["pooled"]:
                    ks = [k for k in common if ds == "pooled" or k[0] == ds]
                    w = sum(1 for k in ks if u[base][k] and not u[o][k])
                    l_ = sum(1 for k in ks if u[o][k] and not u[base][k])
                    print(f"| {rname} | {o} | {ds} | {len(ks)} | {100 * sum(u[base][k] for k in ks) / len(ks):.1f} | "
                          f"{100 * sum(u[o][k] for k in ks) / len(ks):.1f} | {w}/{l_} | {mcnemar(w, l_):.2g} |")
                # cluster definitions
                defs = {}
                if title.startswith("G2"):
                    comp = {}
                    for ds in dss:
                        comp.update({(ds, q): c for q, c in
                                     evidence_components(ds, sorted(k[1] for k in common if k[0] == ds), gs[ds]).items()})
                    defs["shared-evidence component"] = lambda k: comp[k]
                    defs["question"] = lambda k: k
                elif not paired:
                    defs["subject"] = lambda k: (k[0], gs[k[0]][k[1]]["subject"])
                    defs["family"] = lambda k: (k[0], surname(k[0], gs[k[0]][k[1]]["subject"]))
                    defs["question"] = lambda k: k
                else:
                    # a pair has two questions whose subjects can differ; link pairs that share either
                    # subject, or any gold evidence event of either member (family links join each whole world, so
                    # they are not used: two clusters cannot give an interval)
                    sub = link_components(sorted(common), lambda k: [("s", gs[k[0]][q]["subject"]) for q in mem[base][k]])
                    evi = link_components(sorted(common), lambda k: [("e", e) for q in mem[base][k]
                                                                     for e in (gs[k[0]][q].get("evidence_core") or [])])
                    defs["pairs linked by either subject"] = lambda k: sub[k]
                    defs["pairs linked by shared evidence"] = lambda k: evi[k]
                    defs["pair"] = lambda k: k
                for dname, f in defs.items():
                    agg = defaultdict(lambda: [0, 0])
                    for k in sorted(common):
                        c = f(k)
                        agg[c][0] += 100 * (u[base][k] - u[o][k])
                        agg[c][1] += 1
                    est, lo, hi = boot(agg)
                    clus_rows.append((rname, o, dname, len(agg), est, lo, hi))
        print("\n| Reader | other | cluster unit | clusters | difference | 95% interval |")
        print("|---|---|---|---|---|---|")
        for rname, o, dname, nc, est, lo, hi in clus_rows:
            print(f"| {rname} | {o} | {dname} | {nc} | {est:+.1f} | [{lo:+.1f}, {hi:+.1f}] |")
        print()
    # C06: zero / non-zero split of G2
    print("## G2 counting: questions whose gold count is zero vs non-zero (event index vs gold evidence paragraphs)\n")
    print("| Reader | subset | n | event index | gold paragraphs | w/l | exact p (uncorrected) |")
    print("|---|---|---|---|---|---|---|")
    dss = ["agg2_s11", "agg2_s12"]
    gs = {ds: gold(ds) for ds in dss}
    for rname, r in READERS:
        a, b = {}, {}
        for ds in dss:
            a.update({(ds, q): int(x["correct"]) for q, x in load(ds, "mem-evx4v5", r).items()})
            b.update({(ds, q): int(x["correct"]) for q, x in load(ds, "oracle_para", r).items()})
        common = set(a) & set(b)
        for lab, f in (("gold = 0", lambda k: gs[k[0]][k[1]]["answer"]["gold"] == 0),
                       ("gold > 0", lambda k: gs[k[0]][k[1]]["answer"]["gold"] != 0), ("all", lambda k: True)):
            ks = [k for k in common if f(k)]
            w = sum(1 for k in ks if a[k] and not b[k])
            l_ = sum(1 for k in ks if b[k] and not a[k])
            print(f"| {rname} | {lab} | {len(ks)} | {sum(a[k] for k in ks)} | {sum(b[k] for k in ks)} | {w}/{l_} | "
                  f"{mcnemar(w, l_):.2g} |")


if __name__ == "__main__":
    main()
