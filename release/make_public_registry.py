"""Build the public experiment registry from the released result files and their released judge files.

python release/make_public_registry.py      # writes release/EXPERIMENT_REGISTRY_PUBLIC.md

One row per answer file in runs/results/ and runs/results_oolong/: the files listed in release/PUBLIC_FILES.txt when
that list exists (the authors' working tree), otherwise every file present (a copy of the release). Columns are parsed
from the file name; 'answers' counts the lines; 'judged' names the judge files under runs/judged_gpt/,
runs/judged_gpt_block/ and runs/judged_sonnet_block/; 'replay' marks the files listed in
release/STORED_OUTPUTS_SHA256.txt, i.e. read by release/reproduce_tables.py.
"""
import collections
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIST = os.path.join(ROOT, "release", "PUBLIC_FILES.txt")
DIRS = ("runs/results/", "runs/results_oolong/")
released = None  # every released file, when the list exists: judge files are looked up in it, not on disk
if os.path.exists(LIST):
    released = {l.strip().replace("\r", "") for l in open(LIST, encoding="utf-8") if l.strip()}
    files = [f for f in released if f.startswith(DIRS)]
else:
    files = [d + f for d in DIRS if os.path.isdir(os.path.join(ROOT, d)) for f in os.listdir(os.path.join(ROOT, d))]
files = sorted(f for f in files if f.endswith(".jsonl"))
replayed = set()
sp = os.path.join(ROOT, "release", "STORED_OUTPUTS_SHA256.txt")
if os.path.exists(sp):
    replayed = {l.split(None, 1)[1].strip() for l in open(sp, encoding="utf-8") if l.strip() and not l.startswith("#")}
DATA = sorted((d for d in os.listdir(os.path.join(ROOT, "data")) if os.path.isdir(os.path.join(ROOT, "data", d))),
              key=len, reverse=True)
BENCH = [("saga_", "LongState-Saga"), ("cont", "LongState-Continuity"), ("agg2_", "LongState-Aggregate, event-kind questions (G2)"),
         ("agg_", "LongState-Aggregate"), ("code_", "LongState-Code"), ("ama_", "AMA-Bench"), ("nhq_", "NovelHopQA"),
         ("locomo_", "LoCoMo"), ("test", "Oolong-real (test split)"), ("validation", "Oolong-real (validation split)")]
READER = re.compile(r"_((?:claude|claudethink\d+|ollama|ollamathink|codex|agy)-.+?)(?:_b(\d+))?((?:_[^_]+)*)$")
# names with a budget: the reader runs up to the budget, so Ollama tags with underscores (q4_K_M, q8_0) stay whole
READER_B = re.compile(r"_((?:claude|claudethink\d+|ollama|ollamathink|codex|agy)-.+?)_b(\d+)((?:_[^_]+)*)$")


def parse(path):
    stem = os.path.basename(path)[:-6]
    if path.startswith("runs/results_oolong/"):
        ds, rest = stem.split("_", 1)
    else:
        ds = next((d for d in DATA if stem.startswith(d + "_")), stem.split("_")[0])
        rest = stem[len(ds) + 1:]
    m = READER_B.search("_" + rest) or READER.search("_" + rest)
    if not m:
        return ds, "", rest, "", "", ""
    head = ("_" + rest)[:m.start()].lstrip("_")
    length, method = (head.split("_", 1) + [""])[:2] if re.match(r"(d[\d.]+|full)_", head) else ("", head)
    return ds, length, method, m.group(1), m.group(2) or "", m.group(3).lstrip("_")


def judged(stem):
    return ", ".join(name for d, name in (("judged_gpt", "GPT"), ("judged_gpt_block", "GPT (block)"),
                                         ("judged_sonnet_block", "Sonnet (block)"))
                     if (f"runs/{d}/{stem}.json" in released if released is not None
                         else os.path.exists(os.path.join(ROOT, "runs", d, stem + ".json"))))


rows = collections.defaultdict(list)
for f in files:
    p = os.path.join(ROOT, f)
    n = sum(1 for l in open(p, encoding="utf-8") if l.strip()) if os.path.exists(p) else 0
    ds, length, method, reader, budget, tag = parse(f)
    rows[ds].append((length, method, reader, budget, tag, n, judged(os.path.basename(f)[:-6]),
                     "yes" if f in replayed else ""))


ALL = bool(replayed) and all(f in replayed for f in files)


def bench(ds):
    return next((b for p, b in BENCH if ds.startswith(p)), ds)


out = ["# Experiment registry of this release", "",
       f"One row per answer file in this release ({len(files)} files in runs/results/ and runs/results_oolong/, "
       f"{len(rows)} data sets), generated by release/make_public_registry.py from the files themselves. Columns: "
       "length (d1 = 43k tokens, d16 = about 0.5M, d64 = about 1.9M for LongState-Saga; full = the whole record), "
       "method, reader (as in the file name: `claudethink8000` and `ollamathink` = thinking on, the Ollama tag gives "
       "size and quantization), reading budget in tokens, tag (prompt variant, ablation or builder), answers (lines in "
       "the file), judged (the released files of the free-form judges under runs/judged_*)"
       + (", replay (among the stored inputs of release/reproduce_tables.py)" if not ALL else
          "; every file listed is among the stored inputs of release/reproduce_tables.py "
          "(release/STORED_OUTPUTS_SHA256.txt)") + ". Runs that no "
       "reported number uses are not part of the release.",
       ""]
for ds in sorted(rows):
    out += [f"## {ds} ({bench(ds)}; {len(rows[ds])} files)", "",
            "| length | method | reader | budget | tag | answers | judged |" + ("" if ALL else " replay |"),
            "|---|---|---|---|---|---|---|" + ("" if ALL else "---|")]
    out += ["| " + " | ".join(str(c) for c in (r[:-1] if ALL else r)) + " |" for r in sorted(rows[ds])]
    out.append("")
open(os.path.join(ROOT, "release", "EXPERIMENT_REGISTRY_PUBLIC.md"), "w", encoding="utf-8", newline="\n").write(
    "\n".join(out))
print(len(files), "answer files,", len(rows), "data sets,", sum(1 for f in files if f in replayed), "read by the replay")
